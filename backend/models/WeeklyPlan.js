// ─────────────────────────────────────────────────────────────
// WeeklyPlan.js — Mongoose Model for 7-Day Batch Content Sprints
// Manages weekly content calendar blueprint, daily post slots,
// parallel generation states, and individual post approvals.
// ─────────────────────────────────────────────────────────────
const mongoose = require("mongoose");

const WeeklyPlanSlotSchema = new mongoose.Schema({
  slotId: { type: String, required: true }, // e.g., "mon-1", "tue-1"
  dayName: { type: String, required: true }, // "Monday", "Tuesday", etc.
  date: { type: Date, required: true },
  time: { type: String, default: "10:00" }, // "10:00" (editable by user)
  platform: {
    type: String,
    enum: ["instagram", "facebook", "youtube", "tiktok", "linkedin", "twitter"],
    default: "instagram",
  },
  format: {
    type: String,
    enum: ["image", "carousel", "reel", "text", "video"],
    default: "image",
  },

  // Strategic Blueprint (generated by WeeklyPlannerAgent)
  topic: { type: String, default: "" },
  hook: { type: String, default: "" },
  imagePrompt: { type: String, default: "" },

  // Generated Content (filled as parallel workers complete)
  caption: { type: String, default: "" },
  hashtags: { type: [String], default: [] },
  mediaUrls: { type: [String], default: [] }, // 1 URL for single, multiple for carousel slides

  // State Machine
  status: {
    type: String,
    enum: ["blueprint", "generating", "ready", "failed"],
    default: "blueprint",
    index: true,
  },
  isApproved: { type: Boolean, default: false, index: true },
  error: { type: String, default: null },

  // Quality Assurance & Evaluation
  qualityReport: { type: Object, default: null },

  // Link to live scheduled post in Post collection
  postId: { type: mongoose.Schema.Types.ObjectId, ref: "Post", default: null },
});

const WeeklyPlanSchema = new mongoose.Schema(
  {
    userId: { type: mongoose.Schema.Types.ObjectId, ref: "User", index: true },
    productId: { type: mongoose.Schema.Types.ObjectId, ref: "Product", required: true, index: true },
    weekStartDate: { type: Date, required: true },
    weekEndDate: { type: Date, required: true },
    campaignGoal: {
      type: String,
      default: "Engagement & Brand Growth",
    },
    platforms: {
      type: [String],
      default: ["instagram"],
    },

    overallStatus: {
      type: String,
      enum: ["blueprint", "generating", "review", "scheduled", "partial_scheduled"],
      default: "blueprint",
      index: true,
    },

    slots: [WeeklyPlanSlotSchema],
  },
  { timestamps: true }
);

// Compound index for quick lookup of active plans per project
WeeklyPlanSchema.index({ productId: 1, weekStartDate: -1 });

module.exports = mongoose.model("WeeklyPlan", WeeklyPlanSchema);

