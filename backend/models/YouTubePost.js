// ─────────────────────────────────────────────────────────────
// YouTubePost.js — Mongoose Model for YouTube Posts & Shorts
// Supports video upload (.mp4/.mov), custom AI thumbnail attachment,
// CTR-optimized titles, SEO descriptions with timestamps, and scheduling.
// ─────────────────────────────────────────────────────────────
const mongoose = require("mongoose");

const YouTubePostSchema = new mongoose.Schema(
    {
        userId: { type: mongoose.Schema.Types.ObjectId, ref: "User", index: true },
        productId: { type: mongoose.Schema.Types.ObjectId, ref: "Product", index: true },
        productProfile: { type: Object },
        brief: { type: Object },

        // Format: "short" (Vertical 9:16) or "video" (Standard 16:9)
        contentType: {
            type: String,
            enum: ["short", "video"],
            default: "short",
            required: true,
        },

        status: {
            type: String,
            enum: ["draft", "approved", "scheduled", "publishing", "published", "failed"],
            default: "draft",
            index: true,
        },

        // Scheduling support
        scheduledAt: { type: Date, index: true },

        // Video metadata & content
        content: {
            title: { type: String, required: true, maxlength: 100 },
            description: { type: String, default: "" },
            tags: { type: [String], default: [] },
            categoryId: { type: String, default: "22" }, // 22 = People & Blogs, 28 = Science & Tech
            privacyStatus: {
                type: String,
                enum: ["public", "unlisted", "private"],
                default: "public",
            },
            madeForKids: { type: Boolean, default: false },
            hooks: { type: [String], default: [] },
            chapters: [
                {
                    time: { type: String }, // e.g. "0:00"
                    title: { type: String }, // e.g. "Intro"
                    _id: false,
                },
            ],
            visual: {
                brief: { type: String },
                onImageText: { type: String },
                style: { type: String },
            },
        },

        // The uploaded video file (.mp4 / .mov)
        video: {
            url: { type: String },
            filename: { type: String },
            mimeType: { type: String, default: "video/mp4" },
            size: { type: Number },
            duration: { type: Number },
        },

        // The custom thumbnail (generated by AI or uploaded)
        thumbnail: {
            url: { type: String },
            source: { type: String, enum: ["ai", "upload", "generated"], default: "ai" },
            overlayText: { type: String },
        },

        // Live YouTube publication details
        youtube: {
            videoId: { type: String },
            videoUrl: { type: String },
            thumbnailUrl: { type: String },
            publishedAt: { type: Date },
            error: { type: String },
            rawResponse: { type: Object },
        },

        // Versioning & AI revisions history
        revisions: [
            {
                by: { type: String, enum: ["ai", "user"] },
                prompt: String,
                at: { type: Date, default: Date.now },
                _id: false,
            },
        ],
    },
    { timestamps: true }
);

module.exports = mongoose.model("YouTubePost", YouTubePostSchema);

